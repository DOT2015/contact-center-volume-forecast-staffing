"""Recovered estimates vs. data/truth/planted_effects.json, and report consistency."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def test_dow_recovered(results, truth):
    e = results["effects"]
    for d, v in truth["parameters"]["dow_relative_to_thursday"].items():
        if d == "Thu":
            continue
        lo, hi = e["dow_index_ci"][d]
        assert lo <= v <= hi, d


def test_intraday_and_trend(results, truth):
    e = results["effects"]
    assert abs(e["intraday_peak_10_to_1130"] - 1.6) < 0.03
    assert abs(e["intraday_peak_13_to_1430"] - 1.3) < 0.03
    lo, hi = e["trend_per_month_ci"]
    assert lo <= truth["parameters"]["trend_per_month"] <= hi


def test_billing_and_outage(results, truth):
    e = results["effects"]
    lo, hi = e["billing_cycle_lift_ci"]
    assert lo <= truth["parameters"]["billing_cycle_lift"] <= hi
    lo, hi = e["outage_calls_per_customer_ci"]
    assert lo <= truth["realized"]["outage_slope_realized"] <= hi


def test_price_notice(results, truth):
    pn, p = results["price_notice"], truth["parameters"]["price_notice"]
    assert pn["lift_day0_ci"][0] <= p["lift_day0"] <= pn["lift_day0_ci"][1]
    assert pn["half_life_ci"][0] <= p["half_life_days"] <= pn["half_life_ci"][1]
    assert pn["aht_lift_ci"][0] <= truth["realized"]["notice_aht_ratio_realized"] - 1 <= pn["aht_lift_ci"][1]


def test_forecast_beats_naive(results):
    tw = results["backtest"]["total_wape"]
    assert tw["regression"] < tw["naive"]
    assert results["backtest"]["total_mase"]["regression"] < 1
    assert 0.7 <= results["backtest"]["pi80_coverage"] <= 0.9
    assert len(results["backtest"]["origins"]) == 8


def test_staffing_consistent(results):
    st = results["staffing"]
    assert st["scenario_required_fte_peak"] >= st["baseline_required_fte_peak"]
    assert st["ot_cost_scenario"] >= st["ot_cost_baseline"] >= 0
    assert st["hires_needed"] >= 0


def test_readme_filled(results):
    readme = (ROOT / "README.md").read_text()
    assert "{" not in re.sub(r"```.*?```", "", readme, flags=re.S)
    assert f"{100 * results['backtest']['total_wape']['regression']:.1f}%" in readme
    assert "All data in this repository is synthetic, generated by `src/generate_data.py` (seed 42)" in readme
